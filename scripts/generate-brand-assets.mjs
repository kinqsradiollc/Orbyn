function text(value, x, baseline, size, ink, weight = 500, family = dm) {
  const font = family[weight] ?? family[500],
    scale = size / font.unitsPerEm;
  const run = font.layout(value);
  let cursor = 0;
  const paths = run.glyphs
    .map((glyph, i) => {
      const pos = run.positions[i];
      const path = `<path transform="translate(${cursor + pos.xOffset} ${pos.yOffset})" d="${glyph.path.toSVG()}"/>`;
      cursor += pos.xAdvance;
      return path;
    })
    .join("");
  return `<g transform="translate(${x} ${baseline}) scale(${scale} ${-scale})" fill="${ink}">${paths}</g>`;
}
